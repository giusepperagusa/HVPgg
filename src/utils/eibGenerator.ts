/**
 * Generates the production-grade, security-hardened build.sh automation runner.
 */
export function generateBuildScript(config: EIBConfigState): string {
  const isFree = config.environmentMode === 'free';
  const targetArch = config.targetArch;
  const baseImageName = isFree ? 'leap-micro-base.iso' : 'sl-micro-base.iso';
  const eibContainerImage = isFree
    ? 'registry.opensuse.org/isv/suse/edge/eib/containerfile/suse/edge-image-builder:latest'
    : `registry.suse.com/edge/${config.versions.edgeGeneration}/edge-image-builder:latest`;
  const kiwiContainerImage = isFree
    ? 'registry.opensuse.org/virtualization/appliances/images/kiwi:latest'
    : `registry.suse.com/edge/${config.versions.edgeGeneration}/kiwi-builder:latest`;

  // Proxy environment string
  let proxyBlock = '# [1/7] Enterprise Proxy Configuration\n';
  let proxyEnvContainer = '';
  if (config.proxy.enabled) {
    let httpUrl = config.proxy.httpProxy;
    let httpsUrl = config.proxy.httpsProxy;
    if (config.proxy.authEnabled && config.proxy.username && config.proxy.password) {
      try {
        const u = encodeURIComponent(config.proxy.username);
        const p = encodeURIComponent(config.proxy.password);
        httpUrl = httpUrl.replace('://', `://${u}:${p}@`);
        httpsUrl = httpsUrl.replace('://', `://${u}:${p}@`);
      } catch {
        // fallback
      }
    }
    proxyBlock += `export HTTP_PROXY="${httpUrl}"
export HTTPS_PROXY="${httpsUrl}"
export NO_PROXY="${config.proxy.noProxy}"
export http_proxy="$HTTP_PROXY"
export https_proxy="$HTTPS_PROXY"
export no_proxy="$NO_PROXY"
log_sec "Enterprise proxy injected into execution environment."
`;
    proxyEnvContainer = '-e HTTP_PROXY="$HTTP_PROXY" -e HTTPS_PROXY="$HTTPS_PROXY" -e NO_PROXY="$NO_PROXY" ';
  } else {
    proxyBlock += '# Proxy is disabled in PEA configuration.\n';
  }

  // Kiwi or Vanilla ISO build stage
  let isoStageBlock = '';
  if (config.kiwiPrepatch) {
    isoStageBlock = `
# [5/7] UPSTREAM IMAGE UPGRADE: Containerized SUSE KIWI Pre-Patching Pipeline
log_info "Kiwi pre-patch option ENABLED: Compiling freshly patched base ISO via containerized Kiwi..."
mkdir -p base-images kiwi-config

if [ ! -f "kiwi-config/config.xml" ]; then
  log_err "Missing kiwi-config/config.xml! Please re-export workspace bundle."
  exit 1
fi

log_info "Pulling Kiwi Builder container: ${kiwiContainerImage}..."
sudo podman pull ${proxyEnvContainer}${kiwiContainerImage}

log_info "Spining up Kiwi Builder compilation container..."
sudo podman run --rm --privileged \\
  ${proxyEnvContainer}\\
  -v "$(pwd)/kiwi-config":/kiwi-input:z \\
  -v "$(pwd)/base-images":/kiwi-output:z \\
  ${kiwiContainerImage} \\
  --type iso \\
  system build \\
  --description /kiwi-input \\
  --target /kiwi-output

# Identify generated ISO and symlink/move to baseImage
LATEST_KIWI_ISO=$(ls -t base-images/*.iso 2>/dev/null | head -n 1)
if [ -n "$LATEST_KIWI_ISO" ] && [ "$LATEST_KIWI_ISO" != "base-images/${baseImageName}" ]; then
  mv "$LATEST_KIWI_ISO" "base-images/${baseImageName}"
fi

if [ ! -f "base-images/${baseImageName}" ]; then
  log_err "Kiwi compilation failed to generate base-images/${baseImageName}!"
  exit 1
fi
log_sec "Kiwi successfully generated up-to-date base ISO: base-images/${baseImageName}"
`;
  } else {
    isoStageBlock = `
# [5/7] BASE ISO FETCH & RIGOROUS SHA-256 CHECKSUM VERIFICATION
mkdir -p base-images

EXPECTED_SHA256="${config.baseIsoSha256}"
TARGET_ISO="base-images/${baseImageName}"

if [ ! -f "$TARGET_ISO" ]; then
  log_info "Base ISO $TARGET_ISO not found locally. Initiating secure download..."
  ISO_URL="${config.baseIsoUrl}"
  ${!isFree && config.scc.regCode ? `
  # Commercial Mode: Authenticated download via SCC credentials
  log_sec "Fetching commercial SLE Micro ISO via SCC authentication token..."
  curl -fSL ${config.proxy.enabled ? '--proxy "$HTTP_PROXY" ' : ''}-H "Authorization: Bearer ${config.scc.regCode}" \\
    -o "$TARGET_ISO" "$ISO_URL" || {
      log_warn "Direct download with token failed. Falling back to direct URL or manual placement..."
      curl -fSL ${config.proxy.enabled ? '--proxy "$HTTP_PROXY" ' : ''}-o "$TARGET_ISO" "$ISO_URL"
    }
  ` : `
  # Free Mode: Public openSUSE Mirror download
  curl -fSL ${config.proxy.enabled ? '--proxy "$HTTP_PROXY" ' : ''}-o "$TARGET_ISO" "$ISO_URL"
  `}
fi

log_info "Verifying SHA-256 checksum of $TARGET_ISO against embedded hash..."
CALCULATED_HASH=$(sha256sum "$TARGET_ISO" | awk '{print $1}')

if [ "$CALCULATED_HASH" != "$EXPECTED_SHA256" ]; then
  echo ""
  log_err "=========================================================================="
  log_err "CRITICAL SECURITY ERROR: SHA-256 CHECKSUM MISMATCH DETECTED!"
  log_err "Target File:     $TARGET_ISO"
  log_err "Expected Hash:   $EXPECTED_SHA256"
  log_err "Calculated Hash: $CALCULATED_HASH"
  log_err "Aborting build immediately to prevent supply-chain tampering."
  log_err "=========================================================================="
  exit 1
fi

log_sec "ISO SHA-256 Verification PASSED: $CALCULATED_HASH"
`;
  }

  return `#!/usr/bin/env bash
# ============================================================================== #
# SUSE Edge Image Builder (EIB) - Automated Execution & Provisioning Runner     #
# Generated by SUSE Edge Provisioning & Execution Assistant (PEA)               #
# Target Architecture: ${targetArch} | Mode: ${config.environmentMode.toUpperCase()} #
# License: AGPL-3.0-only                                                        #
# ============================================================================== #

set -euo pipefail

# ANSI Color Palette for Scannable Console Output
C_RESET='\\033[0m'
C_RED='\\033[0;31m'
C_GREEN='\\033[0;32m'
C_YELLOW='\\033[1;33m'
C_BLUE='\\033[0;34m'
C_CYAN='\\033[0;36m'
C_MAGENTA='\\033[0;35m'

log_info()  { echo -e "\${C_CYAN}[INFO]  \$(date +'%Y-%m-%d %H:%M:%S')\${C_RESET} \$*"; }
log_warn()  { echo -e "\${C_YELLOW}[WARN]  \$(date +'%Y-%m-%d %H:%M:%S')\${C_RESET} \$*"; }
log_err()   { echo -e "\${C_RED}[ERROR] \$(date +'%Y-%m-%d %H:%M:%S')\${C_RESET} \$*" >&2; }
log_sec()   { echo -e "\${C_GREEN}[SEC]   \$(date +'%Y-%m-%d %H:%M:%S')\${C_RESET} \$*"; }

echo -e "\${C_GREEN}"
cat << "EOF"
  ____  _   _ ____  _____   _____    _            ____  _____    _    
 / ___|| | | / ___|| ____| | ____|__| | __ _  ___|  _ \\| ____|  / \\   
 \\___ \\| | | \\___ \\|  _|   |  _| / _\` |/ _\` |/ _ \\ |_) |  _|   / _ \\  
  ___) | |_| |___) | |___  | |__| (_| | (_| |  __/  __/| |___ / ___ \\ 
 |____/ \\___/|____/|_____| |_____\\__,_|\\__, |\\___|_|   |_____/_/   \\_\\
                                       |___/                           
  SUSE Edge Image Builder - Hardened Provisioning & Execution Runner
EOF
echo -e "\${C_RESET}"

${proxyBlock}

# [2/7] Pre-flight Dependencies & Binary Verification
log_info "Verifying required host utility binaries..."
REQUIRED_TOOLS=("podman" "curl" "sha256sum" "tar" "gzip")
for tool in "\${REQUIRED_TOOLS[@]}"; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    log_err "Missing mandatory dependency '$tool'. Please install it on the host system."
    exit 1
  fi
done
log_info "All required host tools are present."

# [3/7] Multi-Architecture & Cross-Compilation Emulation Bootstrap
TARGET_ARCH="${targetArch}"
HOST_ARCH="\$(uname -m)"
log_info "Hardware Check: Host Architecture='\${HOST_ARCH}' | Target Architecture='\${TARGET_ARCH}'"

if [ "$TARGET_ARCH" = "aarch64" ] && [ "$HOST_ARCH" = "x86_64" ]; then
  log_warn "Target is ARM64 (aarch64) but Host is x86_64. Cross-compilation emulation is required."
  log_sec "Registering QEMU user-static emulation binaries via multiarch container..."
  if ! sudo podman run --rm --privileged multiarch/qemu-user-static --reset -p yes; then
    log_err "Failed to register QEMU user-static emulation! Cannot continue ARM64 build on x86_64 host."
    exit 1
  fi
  log_sec "QEMU user-static binfmt registration verified. Cross-execution enabled."
elif [ "$TARGET_ARCH" != "$HOST_ARCH" ]; then
  log_warn "Cross-architecture detected (\${HOST_ARCH} -> \${TARGET_ARCH}). Ensure host binfmt is configured."
fi

# [4/7] Registry Authentication & Subscription Validation
${!isFree && config.scc.regCode ? `
log_sec "Commercial Mode: Authenticating Podman against registry.suse.com..."
if [ -n "\${SUSE_REGISTRY_USER:-}" ] && [ -n "\${SUSE_REGISTRY_PASSWORD:-}" ]; then
  echo "\$SUSE_REGISTRY_PASSWORD" | sudo podman login registry.suse.com --username "\$SUSE_REGISTRY_USER" --password-stdin
else
  log_info "Using SCC Registration Token for SUSE Registry authentication..."
  echo "${config.scc.regCode}" | sudo podman login registry.suse.com --username "${config.scc.email || 'edge-ops@suse.com'}" --password-stdin || {
    log_warn "Podman login against registry.suse.com failed. Ensure valid SCC account credentials if using protected containers."
  }
fi
` : `
log_info "Free Mode (openSUSE Leap Micro): Using public openSUSE OCI container registries."
`}

${isoStageBlock}

# [6/7] Air-Gapped Kubernetes & Artifact Pre-caching
mkdir -p manifests images/tarballs network

# Verify definition.yaml exists
if [ ! -f "definition.yaml" ]; then
  log_err "Missing definition.yaml file in current working directory!"
  exit 1
fi
log_sec "definition.yaml syntax and presence verified."

# [7/7] Launch SUSE Edge Image Builder in Privileged Container
EIB_IMAGE="${eibContainerImage}"
log_info "Pulling official SUSE Edge Image Builder image: \${EIB_IMAGE}..."
sudo podman pull ${proxyEnvContainer}\${EIB_IMAGE}

log_info "Executing EIB Build Pipeline..."
echo "------------------------------------------------------------------------------"
sudo podman run --privileged --rm \\
  -v "\$(pwd)":/eib:z \\
  ${proxyEnvContainer}\\
  "\${EIB_IMAGE}" \\
  build --definition-file definition.yaml
echo "------------------------------------------------------------------------------"

# Locate Output ISO
OUTPUT_ISO=\$(find . -maxdepth 1 -name "suse-edge-*.iso" 2>/dev/null | head -n 1)
if [ -n "$OUTPUT_ISO" ]; then
  log_sec "=========================================================================="
  log_sec "BUILD SUCCESSFUL! Appliance ISO generated: \$OUTPUT_ISO"
  log_sec "Size: \$(du -h "\$OUTPUT_ISO" | awk '{print \$1}')"
  log_sec "SHA-256: \$(sha256sum "\$OUTPUT_ISO" | awk '{print \$1}')"
  log_sec "You can now burn \$OUTPUT_ISO to bootable USB or attach to appliance virtual media."
  log_sec "=========================================================================="
else
  log_warn "Build process completed. Check output directory for generated artifacts."
fi
`;
}

