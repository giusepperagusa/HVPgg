/**
 * Generates the official SUSE Edge Image Builder definition.yaml
 * Reference: https://documentation.suse.com/edge/
 */
export function generateDefinitionYaml(config: EIBConfigState): string {
  const isFree = config.environmentMode === 'free';
  const baseImageName = isFree ? 'leap-micro-base.iso' : 'sl-micro-base.iso';
  const targetDisk = config.targetDisk === 'custom' ? config.customTargetDisk : config.targetDisk;

  const activeNodes = [config.nodes.node1, config.nodes.node2, config.nodes.node3]
    .filter((n) => n.enabled)
    .map((n) => ({
      hostname: n.hostname,
      type: n.role === 'master' ? 'server' : 'agent',
      network: {
        interface: n.interfaceName,
        macAddress: n.macAddress,
      },
    }));

  const definitionObj: Record<string, unknown> = {
    apiVersion: '1.0',
    image: {
      imageType: 'iso',
      baseImage: baseImageName,
      outputImageName: `suse-edge-${config.environmentMode}-${config.versions.k8sEngine}-${config.targetArch}.iso`,
      arch: config.targetArch,
    },
    operatingSystem: {
      kernelArgs: [
        'console=ttyS0,115200',
        'console=tty0',
        'ignition.firstboot=1',
        'systemd.journald.forward_to_console=1',
      ],
      installer: {
        targetDevice: targetDisk,
        unattended: true,
      },
      users: [
        {
          username: 'root',
          encryptedPassword: config.rootPasswordHash,
          sshIdKeys: config.sshAuthorizedKey ? [config.sshAuthorizedKey.trim()] : [],
        },
      ],
      systemd: {
        units: [
          { name: 'sshd.service', enable: true },
          { name: 'NetworkManager.service', enable: true },
        ],
      },
      packages: {
        noGPGCheck: false,
        packageList: [
          'curl',
          'jq',
          'vim',
          'bind-utils',
          'iptables',
          'iproute2',
          'ethtool',
          'conntrack-tools',
          'tar',
          'gzip',
          'nmstate',
        ],
      },
    },
    kubernetes: {
      version: config.versions.k8sVersion,
      network: {
        cni: config.versions.cniPlugin,
        apiVIP: config.apiServerVip,
      },
      nodes: activeNodes,
      clusterToken: config.k8sClusterToken,
    },
  };

  // Add Helm Charts if present
  if (config.helmCharts && config.helmCharts.length > 0) {
    (definitionObj.kubernetes as Record<string, unknown>).helm = {
      charts: config.helmCharts.map((chart) => ({
        name: chart.name,
        repository: chart.repository,
        version: chart.version,
        targetNamespace: chart.targetNamespace,
        createNamespace: chart.createNamespace,
      })),
    };
  }

  // Add Embedded Artifact Registry for Air-Gapped OCI Images
  if (config.containerImages && config.containerImages.length > 0) {
    definitionObj.embeddedArtifactRegistry = {
      containerImages: config.containerImages.map((img) => ({
        name: `${img.image}:${img.tag}`,
      })),
    };
  }

  // Add Commercial SCC registration block if commercial mode
  if (!isFree && config.scc.regCode) {
    (definitionObj.operatingSystem as Record<string, unknown>).scc = {
      registrationCode: config.scc.regCode,
      email: config.scc.email || undefined,
      sccUrl: config.scc.sccUrl || 'https://scc.suse.com',
    };
  }

  return [
    '# ============================================================================== #',
    '# SUSE Edge Image Builder (EIB) - Automated Recipe Definition                    #',
    '# Generated by SUSE Edge Provisioning & Execution Assistant (PEA)               #',
    `# Mode: ${config.environmentMode.toUpperCase()} | Arch: ${config.targetArch} | Date: ${new Date().toISOString()} #`,
    '# License: AGPL-3.0-only                                                        #',
    '# Reference: https://documentation.suse.com/edge/                                #',
    '# ============================================================================== #',
    '',
    yaml.dump(definitionObj, { indent: 2, lineWidth: 120, noRefs: true }),
  ].join('\n');
}

/**
 * Generates NMState YAML network configuration for a given cluster node.
 * Reference: https://nmstate.io/
 */
export function generateNMStateYaml(node: NodeNetworkConfig): string {
  const nmstateObj = {
    interfaces: [
      {
        name: node.interfaceName || 'eth0',
        type: 'ethernet',
        state: 'up',
        'mac-address': node.macAddress,
        ipv4: {
          enabled: true,
          dhcp: false,
          address: [
            {
              ip: node.ipAddress,
              'prefix-length': node.cidr,
            },
          ],
        },
      },
    ],
    routes: {
      config: [
        {
          destination: '0.0.0.0/0',
          'next-hop-address': node.gateway,
          'next-hop-interface': node.interfaceName || 'eth0',
        },
      ],
    },
    'dns-resolver': {
      config: {
        server: node.dnsServers,
      },
    },
  };

  return [
    '# ============================================================================== #',
    `# NMState Node Network Specification: ${node.hostname} (${node.role.toUpperCase()}) #`,
    '# Reference: https://nmstate.io/                                                  #',
    '# ============================================================================== #',
    '',
    yaml.dump(nmstateObj, { indent: 2, lineWidth: 120, noRefs: true }),
  ].join('\n');
}

